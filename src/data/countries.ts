// 获取国家列表
export function getCountryList(): CountryData[] {
  return Object.values(countriesData)
}

// 根据ID获取国家
export function getCountryById(id: string): CountryData | undefined {
  return countriesData[id]
}

// 搜索国家
export function searchCountries(query: string): CountryData[] {
  const lowerQuery = query.toLowerCase()
  return getCountryList().filter(
    (country) =>
      country.name.toLowerCase().includes(lowerQuery) ||
      country.nameEn.toLowerCase().includes(lowerQuery) ||
      country.capital.toLowerCase().includes(lowerQuery)
  )
}

// 获取大洲国家
export function getCountriesByContinent(continent: string): CountryData[] {
  return getCountryList().filter((country) => country.continent.includes(continent))
}
